function reversedString (string){
    return string.split("").reverse().join("")
}
console.log(reversedString("Helloe"));

// The split() method is used in programming to break a single text string into an ordered list or array of smaller substrings based on a chosen character or pattern

// reverse() method is used to reverse the order of elements in an array. When you call this method, the first element becomes the last, the last element becomes the first, and all elements in between are inverted.

// The join() method is used to combine the elements of an array into a single string, with a specified separator between each element. If no separator is provided, it defaults to a comma.